export function buildRtkAdjacency() {
  const adj = {};
  RTK_CITIES.forEach(c => { adj[c.id] = new Set(); });
  RTK_EDGES.forEach(([a, b]) => {
    adj[a].add(b);
    adj[b].add(a);
  });
  return adj;
}

